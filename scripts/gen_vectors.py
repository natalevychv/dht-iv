#!/usr/bin/env python3
"""
gen_vectors.py

Generates test vectors vectors/n<N>_vectors.txt for N = 3..8, shared by the
naive and proposed testbenches.

Each vector line holds 2N integers separated by spaces:

    x0 .. x(N-1) y0 .. y(N-1)

All values are raw Q15.16 integers (real value * 2^16). The inputs are drawn
uniformly from [-1, 1] on the Q15.16 grid; the first N vectors are the unit
vectors e_0 .. e_(N-1). The expected outputs y = C(N) * x are computed in
double precision from the DHT-IV definition (dht_common.dht_iv_matrix) and
rounded to the nearest Q15.16 value, so a testbench compares them with a
tolerance of a few LSB. Lines starting with '#' are comments.

Usage:
    python3 scripts/gen_vectors.py                 # generate N = 3..8
    python3 scripts/gen_vectors.py 4 6             # generate selected N
    python3 scripts/gen_vectors.py --count 5000    # random vectors per N
    python3 scripts/gen_vectors.py --seed 7        # random seed
"""

import os
import random
import sys

from dht_common import ALL_N, REPO_ROOT, dht_iv_matrix

FRAC_BITS = 16
ONE = 1 << FRAC_BITS
DEFAULT_COUNT = 1000
DEFAULT_SEED = 1


def option(argv, name, default):
    """Value of '--name <int>' in argv, or default."""
    if name in argv:
        return int(argv[argv.index(name) + 1])
    return default


def generate(N, count, seed):
    C = dht_iv_matrix(N)
    rng = random.Random(seed * 100 + N)

    xs = [[ONE if n == k else 0 for n in range(N)] for k in range(N)]
    xs += [[rng.randint(-ONE, ONE) for _ in range(N)] for _ in range(count)]

    L = [f"# n{N}_vectors.txt - generated by scripts/gen_vectors.py, do not edit",
         f"# N = {N}, unit vectors: {N}, random vectors: {count}, seed: {seed}",
         "# Line format: x0 .. x(N-1) y0 .. y(N-1)",
         f"# Raw Q15.16 integers (value * 2^{FRAC_BITS}), y = C({N}) * x rounded"]
    for x in xs:
        y = [round(sum(C[k][n] * x[n] for n in range(N))) for k in range(N)]
        L.append(" ".join(str(v) for v in x + y))
    L.append("")
    return "\n".join(L), len(xs)


def main(argv):
    count = option(argv, "--count", DEFAULT_COUNT)
    seed = option(argv, "--seed", DEFAULT_SEED)
    skip = {i + 1 for i, a in enumerate(argv) if a in ("--count", "--seed")}
    Ns = [int(a) for i, a in enumerate(argv) if a.isdigit() and i not in skip] or list(ALL_N)

    os.makedirs(os.path.join(REPO_ROOT, "vectors"), exist_ok=True)
    for N in Ns:
        text, n_vec = generate(N, count, seed)
        path = os.path.join(REPO_ROOT, "vectors", f"n{N}_vectors.txt")
        with open(path, "w") as f:
            f.write(text)
        print(f"N={N}: {n_vec} vectors -> {os.path.relpath(path, REPO_ROOT)}")


if __name__ == "__main__":
    main(sys.argv[1:])
