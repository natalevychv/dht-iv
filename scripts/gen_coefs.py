#!/usr/bin/env python3
"""
gen_coefs.py

Generates the coefficient packages of the proposed DHT-IV modules
src/proposed/n<N>/n<N>_coef_pkg.vhd for N = 3..8.

The coefficient values come from proposed_coefs.COEFS, computed in double
precision. Each "S_k" entry becomes a constant C_COEF_S_k_N of type
sfix_coef (Q1.30), converted in VHDL with to_sfixed(<value>, 1, -30).

Usage:
    python3 scripts/gen_coefs.py            # generate N = 3..8
    python3 scripts/gen_coefs.py 4 6        # generate selected N
    python3 scripts/gen_coefs.py --report   # print quantization report only
"""

import os
import sys

from dht_common import ALL_N, REPO_ROOT, SEP
from proposed_coefs import COEFS

COEF_HIGH = 1
COEF_LOW = -30


def quantize(v):
    """Value of v rounded to the sfix_coef grid (round to nearest)."""
    return round(v * 2.0 ** -COEF_LOW) * 2.0 ** COEF_LOW


def generate(N):
    coefs = COEFS[N]
    limit = 2.0 ** COEF_HIGH
    for key, v in coefs.items():
        if not -limit <= v < limit:
            raise ValueError(f"N={N} {key} = {v} does not fit in sfix_coef")

    names = {key: f"C_COEF_{key}_{N}" for key in coefs}
    w = max(len(n) for n in names.values()) + 1

    L = [SEP,
         f"-- n{N}_coef_pkg.vhd",
         "--",
         f"-- Coefficients of the proposed {N}-point DHT-IV architecture.",
         "--",
         "-- The values are computed in double precision by",
         "-- scripts/gen_coefs.py (from scripts/proposed_coefs.py) and converted",
         "-- to Q1.30 (sfix_coef) with to_sfixed(). This file is generated by",
         "-- that script - regenerate instead of editing by hand.",
         SEP,
         "library ieee;",
         "use ieee.fixed_pkg.all;",
         "use work.fixed_types_pkg.all;",
         "",
         f"package n{N}_coef_pkg is",
         ""]
    for key, v in coefs.items():
        L.append(f"    constant {names[key]:<{w}}: sfix_coef := "
                 f"to_sfixed({v: .17f}, {COEF_HIGH}, {COEF_LOW});")
    L += ["",
          f"end package n{N}_coef_pkg;",
          ""]

    max_err = max(abs(quantize(v) - v) for v in coefs.values())
    max_abs = max(abs(v) for v in coefs.values())
    return "\n".join(L), dict(count=len(coefs), max_abs=max_abs, max_err=max_err)


def main(argv):
    report_only = "--report" in argv
    Ns = [int(a) for a in argv if a.isdigit()] or list(ALL_N)
    print(f"{'N':>2} {'coefs':>5} {'max|c|':>8} {'max quant err':>14}")
    for N in Ns:
        text, r = generate(N)
        print(f"{N:>2} {r['count']:>5} {r['max_abs']:>8.4f} {r['max_err']:>14.2e}")
        if not report_only:
            path = os.path.join(REPO_ROOT, "src", "proposed", f"n{N}", f"n{N}_coef_pkg.vhd")
            with open(path, "w") as f:
                f.write(text)


if __name__ == "__main__":
    main(sys.argv[1:])
